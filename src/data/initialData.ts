// Generate 30-day realistic attendance dataset across all students and grades
export const generateInitial30DayAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const now = new Date();
  
  const studentList = initialStudents;
  
  // Generate 30 school days backwards
  let daysCount = 0;
  let dayOffset = 0;
  
  while (daysCount < 30) {
    const d = new Date(now);
    d.setDate(now.getDate() - dayOffset);
    dayOffset++;
    
    // Skip Sunday (0)
    if (d.getDay() === 0) continue;
    
    const dateStr = d.toISOString().split('T')[0];
    const isToday = daysCount === 0;
    
    studentList.forEach((st, idx) => {
      let status: 'PRESENT' | 'LATE' | 'PERMISSION' | 'ABSENT' = 'PRESENT';
      let reason: string | undefined = undefined;
      
      // Introduce realistic attendance variations
      const pseudoRandom = Math.sin(dayOffset * 17 + idx * 23);
      
      if (pseudoRandom > 0.88) {
        status = 'LATE';
        reason = 'មកយឺតដោយសារបញ្ហាចរាចរណ៍ (Late 10-15m)';
      } else if (pseudoRandom > 0.82) {
        status = 'PERMISSION';
        reason = 'សុំច្បាប់មានធុរៈគ្រួសារ (Authorized Leave)';
      } else if (pseudoRandom < -0.92) {
        status = 'ABSENT';
        reason = 'អវត្តមានគ្មានច្បាប់ (Unexcused)';
      } else {
        status = 'PRESENT';
      }

      // Ensure today has high present rate
      if (isToday && idx < 6) {
        status = 'PRESENT';
        reason = undefined;
      }
      
      records.push({
        id: `ATT-${dateStr}-${st.id}`,
        studentId: st.id,
        studentCode: st.studentCode,
        studentNameKhmer: st.nameKhmer,
        classId: st.classId,
        className: st.className,
        date: dateStr,
        status,
        reason,
        recordedBy: 'គ្រូបន្ទុកថ្នាក់',
        timestamp: '07:05'
      });
    });
    
    daysCount++;
  }
  
  return records;
};

